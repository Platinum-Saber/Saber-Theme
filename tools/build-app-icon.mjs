// Generates the launcher's adaptive-icon layers from the Figma logo export
// design/logo/saber-logo-classic-metallic.svg. Run: node tools/build-app-icon.mjs
//
// Handles exactly what Figma emits for this logo: paths with solid or
// linear-gradient fill/stroke, luminance masks made of one path (turned into
// clip-paths) and a Gaussian-blur glow (approximated with wide faint strokes,
// since VectorDrawable has no filters).
import { readFileSync, writeFileSync } from 'node:fs';
import { ROOT } from './glyph-source.mjs';

const SVG = `${ROOT}design/logo/saber-logo-classic-metallic.svg`;
const RES = `${ROOT}app/src/main/res/drawable`;
const HEADER = 'Generated by tools/build-app-icon.mjs from design/logo. Do not edit.';

// The logo disc (radius 240 + 5 ring) fills the 66-unit adaptive safe zone.
const SCALE = 66 / 490;
const OFFSET = 54 - 256 * SCALE;
const DISC = '#0B0D10';

const src = readFileSync(SVG, 'utf8');
const attrs = s => Object.fromEntries([...s.matchAll(/([\w:-]+)="([^"]*)"/g)].map(m => [m[1], m[2]]));

const gradients = {};
for (const [, head, body] of src.matchAll(/<linearGradient([^>]*)>([\s\S]*?)<\/linearGradient>/g)) {
  const a = attrs(head);
  gradients[a.id] = {
    ...a,
    stops: [...body.matchAll(/<stop([^>]*)\/>/g)].map(([, s]) => {
      const st = attrs(s);
      return { offset: st.offset ?? '0', color: st['stop-color'] };
    }),
  };
}
const masks = {};
for (const [, head, body] of src.matchAll(/<mask([^>]*)>([\s\S]*?)<\/mask>/g)) {
  masks[attrs(head).id] = attrs(body.match(/<path([^>]*)\/>/)[1]).d;
}

/** Drawing tree: [{ kind: 'path', a } | { kind: 'group', clip?, glow?, children }]. */
function parse() {
  const body = src.slice(0, src.indexOf('<defs>')).replace(/<mask[\s\S]*?<\/mask>/g, '');
  const root = { children: [] };
  const stack = [root];
  for (const [, close, tag, rest] of body.matchAll(/<(\/?)(g|path)([^>]*?)\/?>/g)) {
    if (close) { stack.pop(); continue; }
    const a = attrs(rest);
    if (tag === 'path') { stack.at(-1).children.push({ kind: 'path', a }); continue; }
    const id = v => v?.match(/url\(#([^)]+)\)/)?.[1];
    const group = { kind: 'group', clip: masks[id(a.mask)], glow: !!a.filter, children: [] };
    stack.at(-1).children.push(group);
    stack.push(group);
  }
  return root.children;
}

const hex = c => `#FF${c.slice(1).toUpperCase()}`;
const ind = n => ' '.repeat(n);

function gradientXml(attr, ref, depth) {
  const g = gradients[ref.match(/url\(#([^)]+)\)/)[1]];
  const items = g.stops.map(s => `${ind(depth + 8)}<item android:offset="${s.offset}" android:color="${hex(s.color)}" />`).join('\n');
  return `${ind(depth + 4)}<aapt:attr name="android:${attr}">
${ind(depth + 8)}<gradient android:type="linear" android:startX="${g.x1}" android:startY="${g.y1}" android:endX="${g.x2}" android:endY="${g.y2}">
${items}
${ind(depth + 8)}</gradient>
${ind(depth + 4)}</aapt:attr>`;
}

function pathXml(a, depth, mono, extra = {}) {
  const p = [`android:pathData="${a.d}"`];
  const children = [];
  const alpha = a.opacity;
  const fill = a.fill && a.fill !== 'none' ? a.fill : null;
  const stroke = a.stroke ?? null;
  if (fill) {
    if (mono) p.push('android:fillColor="#FFFFFFFF"');
    else if (fill.startsWith('url')) children.push(gradientXml('fillColor', fill, depth));
    else p.push(`android:fillColor="${hex(fill)}"`);
    if (alpha) p.push(`android:fillAlpha="${alpha}"`);
  }
  if (stroke) {
    if (mono) p.push('android:strokeColor="#FFFFFFFF"');
    else if (stroke.startsWith('url')) children.push(gradientXml('strokeColor', stroke, depth));
    else p.push(`android:strokeColor="${hex(stroke)}"`);
    p.push(`android:strokeWidth="${extra.strokeWidth ?? a['stroke-width'] ?? 1}"`);
    if (a['stroke-linecap']) p.push(`android:strokeLineCap="${a['stroke-linecap']}"`);
    const sa = extra.strokeAlpha ?? alpha;
    if (sa) p.push(`android:strokeAlpha="${sa}"`);
  }
  const open = `${ind(depth)}<path\n${p.map(x => `${ind(depth + 4)}${x}`).join('\n')}`;
  return children.length ? `${open}>\n${children.join('\n')}\n${ind(depth)}</path>` : `${open} />`;
}

/** Monochrome keeps the silhouette: ring, chip outlines, pins, blade, hilt. */
function monoPath(a) {
  if (a.fill === DISC || a.opacity) return null; // disc, grip grooves
  if (a.fill?.startsWith('#') && !a.stroke && a.fill !== '#3DDBA0') return null; // LED dots
  if (a.fill === '#3DDBA0') return null; // hilt button
  if (a.fill === '#12161B') return { ...a, fill: undefined }; // chip bodies: outline only
  return a;
}

function emit(nodes, depth, mono) {
  const out = [];
  for (const n of nodes) {
    if (n.kind === 'path') {
      const a = mono ? monoPath(n.a) : n.a;
      if (a) out.push(pathXml(a, depth, mono));
      continue;
    }
    if (n.glow) {
      if (mono) continue;
      // feGaussianBlur(stdDeviation 7) on a 16-wide stroke ≈ two soft halos.
      for (const [w, al] of [[36, '0.12'], [26, '0.22']]) {
        for (const c of n.children) out.push(pathXml(c.a, depth, false, { strokeWidth: w, strokeAlpha: al }));
      }
      continue;
    }
    if (n.clip) {
      out.push(`${ind(depth)}<group>\n${ind(depth + 4)}<clip-path android:pathData="${n.clip}" />\n${emit(n.children, depth + 4, mono)}\n${ind(depth)}</group>`);
    } else {
      out.push(emit(n.children, depth, mono));
    }
  }
  return out.filter(Boolean).join('\n');
}

function vector(mono) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="${SCALE.toFixed(5)}"
        android:scaleY="${SCALE.toFixed(5)}"
        android:translateX="${OFFSET.toFixed(4)}"
        android:translateY="${OFFSET.toFixed(4)}">
${emit(parse(), 8, mono)}
    </group>
</vector>
`;
}

writeFileSync(`${RES}/ic_launcher_foreground.xml`, vector(false));
writeFileSync(`${RES}/ic_launcher_monochrome.xml`, vector(true));
console.log(`app icon: ${Object.keys(gradients).length} gradients, ${Object.keys(masks).length} masks -> ic_launcher_foreground/monochrome`);
