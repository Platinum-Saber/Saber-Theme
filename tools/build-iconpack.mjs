// Generates the :iconpack resources (glyph icons, appfilter, drawable list)
// from design/icons. Run: node tools/build-iconpack.mjs
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { ROOT, loadGlyphs, resName, toPathData } from './glyph-source.mjs';

const MAIN = `${ROOT}iconpack/src/main`;
const DRAWABLE = `${MAIN}/res/drawable`;
const ANYDPI = `${MAIN}/res/drawable-anydpi`;
const HEADER = 'Generated by tools/build-iconpack.mjs from design/icons. Do not edit.';

// Icons are plain transparent vectors, not adaptive icons: hosts that flatten
// adaptive icons (One UI Theme Park) fill a transparent background with black,
// while a plain vector keeps it transparent. The 24-unit glyph sits centred in
// a 36-unit canvas (two thirds of the icon).
const CANVAS = 36;
const OFFSET = (CANVAS - 24) / 2;

const { APPS } = loadGlyphs();
const components = JSON.parse(readFileSync(`${ROOT}design/icons/components.json`, 'utf8'));
for (const key of Object.keys(components)) {
  if (!APPS[key]) throw new Error(`components.json: unknown glyph "${key}"`);
}

const xmlAttr = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

function icon(paths) {
  const body = paths.map(d => `        <path
            android:pathData="${d}"
            android:strokeColor="#FFFFFFFF"
            android:strokeWidth="1.75"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="48dp"
    android:height="48dp"
    android:viewportWidth="${CANVAS}"
    android:viewportHeight="${CANVAS}">
    <group
        android:translateX="${OFFSET}"
        android:translateY="${OFFSET}">
${body}
    </group>
</vector>
`;
}

for (const dir of [DRAWABLE, ANYDPI, `${MAIN}/res/xml`, `${MAIN}/assets`]) mkdirSync(dir, { recursive: true });
for (const dir of [DRAWABLE, ANYDPI]) {
  for (const f of readdirSync(dir)) if (f.startsWith('ic_') && f !== 'ic_launcher_fg.xml') rmSync(`${dir}/${f}`);
}

// The pack's own launcher icon: the gallery glyph in the 108-unit adaptive
// canvas, inside the 66-unit safe zone (24 * 1.75 = 42 units).
writeFileSync(`${DRAWABLE}/ic_launcher_fg.xml`, icon(toPathData(APPS.gallery[1]))
  .replace('android:width="48dp"', 'android:width="108dp"')
  .replace('android:height="48dp"', 'android:height="108dp"')
  .replace(`android:viewportWidth="${CANVAS}"`, 'android:viewportWidth="108"')
  .replace(`android:viewportHeight="${CANVAS}"`, 'android:viewportHeight="108"')
  .replace(`android:translateX="${OFFSET}"`, `android:scaleX="1.75"
        android:scaleY="1.75"
        android:translateX="33"`)
  .replace(`android:translateY="${OFFSET}"`, 'android:translateY="33"'));

const keys = Object.keys(APPS);
for (const key of keys) {
  const name = `ic_${resName(key)}`;
  writeFileSync(`${ANYDPI}/${name}.xml`, icon(toPathData(APPS[key][1])));
}

const items = Object.entries(components).flatMap(([key, list]) =>
  list.map(c => `    <item component="ComponentInfo{${xmlAttr(c)}}" drawable="ic_${resName(key)}" />`));
const appfilter = `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<resources>
${items.join('\n')}
</resources>
`;
writeFileSync(`${MAIN}/res/xml/appfilter.xml`, appfilter);
writeFileSync(`${MAIN}/assets/appfilter.xml`, appfilter);

writeFileSync(`${MAIN}/res/xml/drawable.xml`, `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<resources>
    <version>1</version>
    <category title="Saber" />
${keys.map(k => `    <item drawable="ic_${resName(k)}" />`).join('\n')}
</resources>
`);

console.log(`iconpack: ${keys.length} icons, ${items.length} components`);
